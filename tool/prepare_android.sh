#!/usr/bin/env bash
# Generates the Android Gradle scaffold with the Flutter SDK installed on the
# build machine (so Gradle/AGP/Kotlin versions always match that SDK), then
# applies the small customisations this app needs.
# Safe to run repeatedly: it only generates android/ when it is missing.
set -euo pipefail

PROJECT_NAME="tickoff_replacement"
ORG="dev.tickoffreplacement"
APP_LABEL="TickOff"

if [ ! -d "android/app" ]; then
  echo "Generating Android scaffold with the installed Flutter SDK..."
  SCAFFOLD_DIR="$(mktemp -d)"
  flutter create --platforms=android \
    --project-name "$PROJECT_NAME" \
    --org "$ORG" \
    "$SCAFFOLD_DIR/$PROJECT_NAME"
  cp -R "$SCAFFOLD_DIR/$PROJECT_NAME/android" ./android
  rm -f android/local.properties
else
  echo "android/ already exists - leaving it untouched."
fi

MANIFEST="android/app/src/main/AndroidManifest.xml"
if [ -f "$MANIFEST" ]; then
  sed -i "s/android:label=\"[^\"]*\"/android:label=\"$APP_LABEL\"/" "$MANIFEST"
  echo "App label set to $APP_LABEL"
else
  echo "ERROR: $MANIFEST not found" >&2
  exit 1
fi

# Permissions required by local reminders, photo capture, and voice notes.
if [ -f "$MANIFEST" ]; then
  grep -q 'android.permission.POST_NOTIFICATIONS' "$MANIFEST" || sed -i '/<application/i\    <uses-permission android:name="android.permission.POST_NOTIFICATIONS" />\n    <uses-permission android:name="android.permission.RECORD_AUDIO" />\n    <uses-permission android:name="android.permission.CAMERA" />\n    <uses-permission android:name="android.permission.RECEIVE_BOOT_COMPLETED" />\n    <uses-permission android:name="android.permission.VIBRATE" />' "$MANIFEST"
fi

# Audio recording plugins require Android 23 or newer.
APP_GRADLE="android/app/build.gradle.kts"
if [ -f "$APP_GRADLE" ]; then
  sed -i 's/minSdk = flutter.minSdkVersion/minSdk = 23/' "$APP_GRADLE"
fi
if [ -f "$APP_GRADLE" ]; then
  # Configure core-library desugaring robustly for the Kotlin DSL template
  # generated by the current Flutter SDK. A plain grep can find a dependency
  # string outside the dependencies block and incorrectly skip adding it.
  python3 - "$APP_GRADLE" <<'PYTHON'
from pathlib import Path
import re
import sys

path = Path(sys.argv[1])
text = path.read_text(encoding="utf-8")

# Enable desugaring inside compileOptions.
if "isCoreLibraryDesugaringEnabled = true" not in text:
    compile_options = re.search(r"(?m)^([ \t]*)compileOptions[ \t]*\{[ \t]*$", text)
    if not compile_options:
        raise SystemExit("ERROR: compileOptions block not found in " + str(path))
    indent = compile_options.group(1) + "    "
    pos = compile_options.end()
    text = text[:pos] + "\n" + indent + "isCoreLibraryDesugaringEnabled = true" + text[pos:]

# Remove any previous desugar_jdk_libs declaration before inserting exactly
# one declaration in the actual dependencies block.
text = re.sub(
    r"(?m)^[ \t]*coreLibraryDesugaring\([\"']com\.android\.tools:desugar_jdk_libs:[^\"']+[\"']\)[ \t]*\n?",
    "",
    text,
)
dependencies = re.search(r"(?m)^([ \t]*)dependencies[ \t]*\{[ \t]*$", text)
if dependencies:
    indent = dependencies.group(1) + "    "
    pos = dependencies.end()
    text = text[:pos] + "\n" + indent + 'coreLibraryDesugaring("com.android.tools:desugar_jdk_libs:2.1.4")' + text[pos:]
else:
    text = text.rstrip() + '\n\ndependencies {\n    coreLibraryDesugaring("com.android.tools:desugar_jdk_libs:2.1.4")\n}\n'

path.write_text(text, encoding="utf-8")
print("Configured core-library desugaring in " + str(path))
PYTHON
fi
